// Generates tales into tales/ (Markdown + JSON) and validates every one. Exit code 1 if any fails.
// Usage: node scripts/generate.mjs [--n 50] [--from 1]
import { writeFileSync, mkdirSync } from 'node:fs';
import { generator, validate, explain, data } from '../src/index.js';
const arg = (k, d) => { const i = process.argv.indexOf('--' + k); return i > 0 ? +process.argv[i + 1] : d; };
const n = arg('n', 50), from = arg('from', 1);
const sym = Object.fromEntries(data.functions.map((f) => [f.id, f.sym]));
mkdirSync(new URL('../tales/', import.meta.url), { recursive: true });
let pass = 0; const index = [];
for (let s = from; s < from + n; s++) {
  const t = generator.generate(s);
  const res = validate(t.moves, { mode: 'strict' });
  if (res.ok) pass++;
  const id = String(s).padStart(3, '0');
  const seq = t.moves.map((m) => m.map((f) => sym[f]).join(' ')).join(' | ');
  const title = `The Tale of ${t.cast.heroShort} and ${t.cast.villain}`;
  writeFileSync(new URL(`../tales/tale-${id}.json`, import.meta.url), JSON.stringify({ seed: t.seed, title, sequence: t.moves, symbols: seq, choices: t.choices, validation: res, pages: t.pages.map((p) => ({ f: p.f, move: p.move, text: (p.pre + (p.post ? ' ' + p.post : '')).trim() })) }, null, 2));
  writeFileSync(new URL(`../tales/tale-${id}.md`, import.meta.url), `# ${title}\n\n*Seed ${t.seed}. Functions: \`${seq}\`. Strict validation: ${res.ok ? 'PASS' : 'FAIL'}.*\n\n` + t.pages.map((p) => (p.pre + (p.post ? ' ' + p.post : '')).trim()).join('\n\n') + '\n');
  index.push(`| ${id} | ${title} | \`${seq}\` | ${res.ok ? 'pass' : 'FAIL'} |`);
  if (!res.ok) console.error(`seed ${s}:\n${explain(res)}`);
}
writeFileSync(new URL('../tales/INDEX.md', import.meta.url), `# Generated tales\n\nAll generated by \`npm run generate\` (seeds ${from}-${from + n - 1}) and checked by the strict validator.\n\n| # | Title | Functions | Strict |\n|---|---|---|---|\n${index.join('\n')}\n`);
console.log(`${pass}/${n} generated tales pass the strict validator`);
process.exit(pass === n ? 0 : 1);
