// Writes reader/data.js (a classic script) from data/grammar.json so the reader works from file://.
import { readFileSync, writeFileSync } from 'node:fs';
const json = readFileSync(new URL('../data/grammar.json', import.meta.url), 'utf8');
const js = '// GENERATED by scripts/sync-data.mjs from data/grammar.json. Do not edit.\nglobalThis.PROPP_DATA = ' + JSON.stringify(JSON.parse(json)) + ';\n';
writeFileSync(new URL('../reader/data.js', import.meta.url), js);
console.log('wrote reader/data.js');
