// Validates the 12 annotated tales in strict and refined modes and writes docs/ACCEPTANCE.md + corpus/results.json.
import { readFileSync, writeFileSync } from 'node:fs';
import { validate, data } from '../src/index.js';
const corpus = JSON.parse(readFileSync(new URL('../corpus/tales.json', import.meta.url), 'utf8'));
const sym = Object.fromEntries(data.functions.map((f) => [f.id, f.sym]));
const fmt = (t) => t.moves.map((mv) => mv.map((e) => sym[e.f] + (e.implicit ? '*' : '')).join(' ')).join('  |  ');
const results = corpus.tales.map((t) => ({ id: t.id, title: t.title, genre: t.genre, atu: t.atu, sequence: fmt(t), strict: validate(t, { mode: 'strict' }), refined: validate(t, { mode: 'refined' }) }));

// Leave-one-family-out: how many tales pass strict if one rule family is ignored.
const families = ['ORDER', 'UNPAIRED', 'MISSING_PREREQ', 'NO_COMPLICATION', 'UNMAPPED'];
const loo = Object.fromEntries(families.map((fam) => [fam, results.filter((r) => r.strict.violations.every((v) => v.code === fam)).length]));
const codeCounts = (mode) => { const c = {}; results.forEach((r) => r[mode].violations.forEach((v) => (c[v.code] = (c[v.code] || 0) + 1))); return c; };
const magic = results.filter((r) => !r.genre.includes('control') && !r.genre.includes('novella'));
const pct = (n, d) => `${n}/${d} (${Math.round((100 * n) / d)}%)`;
const strictN = results.filter((r) => r.strict.ok).length, refinedN = results.filter((r) => r.refined.ok).length;
const summary = {
  tales: results.length,
  strict: pct(strictN, results.length), refined: pct(refinedN, results.length),
  magicOnly: { n: magic.length, strict: pct(magic.filter((r) => r.strict.ok).length, magic.length), refined: pct(magic.filter((r) => r.refined.ok).length, magic.length) },
  violationsByCode: { strict: codeCounts('strict'), refined: codeCounts('refined') },
  strictPassIfOnlyThisFamilyIgnored: loo,
};
writeFileSync(new URL('../corpus/results.json', import.meta.url), JSON.stringify({ summary, results }, null, 2));

let md = `# Acceptance report (generated by \`npm run validate-corpus\`)\n\nSource: Afanas'ev, *Russian Folk-Tales*, tr. L. A. Magnus (1915), Project Gutenberg #62509. Annotations: \`corpus/tales.json\`. \`*\` = implicit function.\n\n`;
md += `| | Strict | Refined |\n|---|---|---|\n| All 12 tales | ${summary.strict} | ${summary.refined} |\n| Magic tales only (${magic.length}) | ${summary.magicOnly.strict} | ${summary.magicOnly.refined} |\n\n`;
md += `Violations by code. Strict: ${JSON.stringify(summary.violationsByCode.strict)}. Refined: ${JSON.stringify(summary.violationsByCode.refined)}.\n\n`;
md += `Tales that would pass strict mode if only one rule family were dropped: ${JSON.stringify(loo)}.\n\n`;
for (const r of results) {
  md += `## ${r.title} (${r.genre}; ATU ${r.atu})\n\n\`${r.sequence}\`\n\n- Strict: **${r.strict.ok ? 'PASS' : 'FAIL'}**${r.strict.ok ? '' : ` (${r.strict.violations.length} violations)`}\n- Refined: **${r.refined.ok ? 'PASS' : 'FAIL'}**${r.refined.refinementsUsed.length ? ` (used ${r.refined.refinementsUsed.join(', ')})` : ''}\n`;
  for (const v of r.refined.violations) md += `  - refined [${v.code}] ${v.move != null ? `move ${v.move + 1}: ` : ''}${v.message}\n`;
  md += '\n';
}
writeFileSync(new URL('../docs/ACCEPTANCE.md', import.meta.url), md);
console.log(JSON.stringify(summary, null, 2));
for (const r of results) console.log(`${r.strict.ok ? 'S' : '-'}${r.refined.ok ? 'R' : '-'} ${r.id.padEnd(20)} ${r.refined.violations.map((v) => v.code + (v.f ? ':' + sym[v.f] : '')).join(', ')}`);
